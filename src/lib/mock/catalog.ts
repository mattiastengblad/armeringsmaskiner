function img(filename: string, id?: string): ProductImage {
  return {
    id: id ?? `img-${filename}`,
    url: `/images/products/${filename}`,
    altText: null,
    sortOrder: 0,
  };
}

function images(filenames: string[]): ProductImage[] {
  return filenames.map((filename, i) => ({
    id: `img-${filename}-${i}`,
    url: `/images/products/${filename}`,
    altText: null,
    sortOrder: i,
  }));
}

function specs(productSlug: string, entries: [string, string][]): ProductSpec[] {
  return entries.map(([specKey, specValue], i) => ({
    id: `spec-${productSlug}-${i}`,
    specKey,
    specValue,
    sortOrder: i,
  }));
}

function capacity(productSlug: string, rows: [string, number][]): ProductCapacityRow[] {
  return rows.map(([barDiameterMm, maxQtySimultaneous], i) => ({
    id: `cap-${productSlug}-${i}`,
    barDiameterMm,
    maxQtySimultaneous,
    sortOrder: i,
  }));
}

function accessories(productSlug: string, names: string[]): Accessory[] {
  return names.map((name, i) => ({
    id: `acc-${productSlug}-${i}`,
    name,
    description: null,
    quantityIncluded: 1,
  }));
}

function doc(
  id: string,
  title: string,
  path: string,
  docType: DocumentItem['docType'],
): DocumentItem {
  return { id, title, fileUrl: path, docType, language: 'sv' };
}

